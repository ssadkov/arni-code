def build_template(path: Path) -> None:
	doc = Document()
	style = doc.styles['Normal']
	style.font.name = 'Times New Roman'
	style.font.size = Pt(11)
	doc.add_heading('ДОГОВОР ВОЗМЕЗДНОГО ОКАЗАНИЯ УСЛУГ № ________', level=1)
	doc.add_paragraph('г. ____________\t\t\t\t\t\t«___» ____________ 20__ г.')
	doc.add_paragraph(
		BLANK + ', БИН ' + BLANK + ', именуемое в дальнейшем «Исполнитель», в лице ' + BLANK
		+ ', действующего на основании ' + BLANK + ', с одной стороны, и ' + BLANK + ', БИН ' + BLANK
		+ ', именуемое в дальнейшем «Заказчик», в лице ' + BLANK + ', действующего на основании ' + BLANK
		+ ', с другой стороны, заключили настоящий Договор о нижеследующем:')
	for title, items in SECTIONS:
		doc.add_heading(title, level=2)
		for item in items:
			doc.add_paragraph(item)
	doc.add_heading('8. Реквизиты и подписи сторон', level=2)
	table = doc.add_table(rows=len(REQUISITES) + 1, cols=3)
	table.style = 'Table Grid'
	table.cell(0, 1).text = 'Исполнитель'
	table.cell(0, 2).text = 'Заказчик'
	for row, label in enumerate(REQUISITES, start=1):
		table.cell(row, 0).text = label
		table.cell(row, 1).text = BLANK
		table.cell(row, 2).text = BLANK
	doc.save(path)


def main() -> None:
	target = Path(sys.argv[1] if len(sys.argv) > 1 else 'C:/work/test-arni-contract').resolve()
	if (target / 'template').exists():
		sys.exit(f'{target} already contains a template; remove it or choose another folder')
	(target / 'template').mkdir(parents=True)
	(target / 'data').mkdir()
	template = target / 'template' / 'Договор_оказания_услуг_РК.docx'
	build_template(template)
	(target / 'data' / 'заказчик.txt').write_text(CUSTOMER_CARD, encoding='utf-8')
	manifest = {'template': template.name, 'sha256': hashlib.sha256(template.read_bytes()).hexdigest()}
	(target / '.case.json').write_text(json.dumps(manifest, ensure_ascii=False, indent='\t'), encoding='utf-8')
	print(f'Created {target}')


if __name__ == '__main__':
	main()
